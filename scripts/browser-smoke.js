async (page) => {
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
  const test = await context.newPage()
  const checks = []
  const errors = []
  test.on('pageerror', error => errors.push(error.message))
  await test.addInitScript(() => { window.confirm = () => true })
  const check = (ok, message) => { if (!ok) throw Error(message); checks.push(message) }
  const origin = 'http://127.0.0.1:5174'
  try {
    await test.goto(origin + '/importar')
    await test.locator('input[type=file]').first().setInputFiles({ name:'smoke.csv', mimeType:'text/csv', buffer:Buffer.from('Data;Descricao;Valor;Tipo\n01/10/2026;Salario;3000,00;C\n02/10/2026;Mercado;1234,56;D') })
    await test.getByRole('button', {name:'Confirmar importação (2)'}).waitFor()
    await test.reload()
    await test.getByRole('button', {name:'Confirmar importação (2)'}).waitFor()
    await test.getByRole('link', {name:'Categorias',exact:true}).click()
    await test.locator('.category-card').first().waitFor()
    checks.push('Revisão preservada na recarga e salva ao abrir Categorias')
    await test.goto(origin + '/extrato')
    await test.getByRole('heading', {name:'Extrato',exact:true}).waitFor()
    check((await test.locator('main').innerText()).includes('1.234,56'), 'CSV e recarga')
    await test.getByRole('button',{name:'Editar lançamento de Mercado',exact:true}).first().click()
    await test.getByLabel('Valor',{exact:true}).fill('1500,50')
    await test.getByRole('button',{name:'Salvar',exact:true}).click()
    await test.reload()
    await test.getByRole('heading',{name:'Extrato',exact:true}).waitFor()
    check((await test.locator('main').innerText()).includes('1.500,50'), 'Edição persistida')
    await test.goto(origin + '/importar')
    await test.locator('input[type=file]').first().setInputFiles({name:'duplicado.csv',mimeType:'text/csv',buffer:Buffer.from('Data;Descricao;Valor;Tipo\n01/10/2026;Salario;3000,00;C')})
    await test.getByRole('button',{name:'Confirmar importação (1)'}).click()
    await test.getByText('Há lançamentos já importados neste arquivo.',{exact:false}).waitFor()
    checks.push('Reimportação bloqueada')
    await test.getByLabel('Valor do lançamento 1').fill('100abc')
    check(await test.getByRole('button',{name:'Confirmar importação (1)'}).isDisabled(),'Prévia inválida bloqueada')
    await test.getByRole('link',{name:'Categorias',exact:true}).click()
    await test.getByRole('button',{name:'Confirmar importação (1)'}).waitFor()
    check(await test.getByLabel('Valor do lançamento 1').inputValue() === '100abc', 'Revisão inválida preservada ao navegar')
    await test.getByRole('button',{name:'Descartar',exact:true}).click()
    const download = test.waitForEvent('download')
    await test.getByRole('button',{name:'Exportar backup',exact:true}).click()
    await (await download).saveAs('.playwright-cli/smoke-backup.json')
    await test.getByLabel('Restaurar backup JSON').setInputFiles('.playwright-cli/smoke-backup.json')
    await test.getByText('Backup restaurado.',{exact:true}).waitFor()
    checks.push('Backup exportado e restaurado')
    for (const [fixture, amount] of [['extrato-texto.pdf','1234,56'], ['extrato-ocr.pdf','100,00']]) {
      await test.goto(origin + '/importar')
      await test.locator('input[type=file]').first().setInputFiles('tests/fixtures/' + fixture)
      await test.getByRole('button',{name:'Confirmar importação (1)'}).waitFor({timeout:90000})
      check(await test.getByLabel('Valor do lançamento 1').inputValue() === amount, fixture)
      await test.getByRole('button',{name:'Descartar',exact:true}).click()
    }
    await test.goto(origin + '/categorias')
    await test.getByText('Definir orçamento do mês selecionado',{exact:true}).click()
    await test.getByLabel('Novo limite',{exact:true}).fill('1800,00')
    await test.getByRole('button',{name:'Salvar limite',exact:true}).click()
    check((await test.locator('main').innerText()).includes('1.800,00'),'Orçamento editável')
    await test.goto(origin)
    await test.locator('.hero-value').waitFor()
    await test.screenshot({path:'.playwright-cli/final-desktop.png',fullPage:true})
    await test.setViewportSize({width:390,height:844})
    check(await test.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Layout mobile')
    await test.screenshot({path:'.playwright-cli/final-mobile.png',fullPage:true})
    await test.goto(origin + '/extrato')
    await test.getByRole('button',{name:'Editar lançamento de Mercado',exact:true}).last().click()
    await test.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Quota de teste') } })
    await test.getByLabel('Valor',{exact:true}).fill('1600,00')
    await test.getByRole('button',{name:'Salvar',exact:true}).click()
    await test.getByRole('alert').filter({hasText:'Não foi possível salvar'}).waitFor()
    checks.push('Falha de quota visível')
    check(errors.length === 0, 'Sem erros JavaScript: ' + errors.join(', '))
    return checks
  } finally { await context.close() }
}
